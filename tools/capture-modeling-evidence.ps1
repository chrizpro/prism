<#
.SYNOPSIS
Capture actual Prism desktop viewport images of the models generated by --extrude-evidence.
.EXAMPLE
./tools/capture-modeling-evidence.ps1
#>
param([string]$EvidenceDirectory = 'artifacts/extrude')
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$output = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($EvidenceDirectory)
if (-not (Test-Path -LiteralPath (Join-Path $output 'solid-distance-result.prism'))) {
    throw 'Run dotnet run --project tests/Prism.DirectModelTests -c Release -- --extrude-evidence first (from the repo root).'
}
& dotnet build (Join-Path $root 'Prism.Desktop') -c Release
if ($LASTEXITCODE -ne 0) { throw 'Desktop build failed' }
$discovery = Join-Path $output ('automation-' + [guid]::NewGuid().ToString('N') + '.json')
$oldDiscovery = $env:PRISM_AUTOMATION_DISCOVERY
$oldHome = $env:PRISM_NO_HOME
$oldAutomation = $env:PRISM_AUTOMATION
$app = $null
try {
    $env:PRISM_AUTOMATION_DISCOVERY = $discovery
    $env:PRISM_NO_HOME = '1'
    $env:PRISM_AUTOMATION = '1'
    $app = Start-Process -FilePath (Join-Path $root 'Prism.Desktop/bin/Release/net10.0/Prism.Desktop.exe') -WorkingDirectory $root -WindowStyle Hidden -PassThru
    $env:PRISM_AUTOMATION_DISCOVERY = $oldDiscovery
    $env:PRISM_NO_HOME = $oldHome
    $env:PRISM_AUTOMATION = $oldAutomation
    $deadline = [DateTime]::UtcNow.AddSeconds(30)
    while (-not (Test-Path -LiteralPath $discovery)) {
        if ($app.HasExited -or [DateTime]::UtcNow -gt $deadline) { throw 'Evidence app did not start its automation bridge' }
        Start-Sleep -Milliseconds 200
    }
    $connection = Get-Content -LiteralPath $discovery -Raw | ConvertFrom-Json
    if ($connection.pid -ne $app.Id) { throw 'Discovery does not identify the evidence process' }
    function Call-Prism([string]$Tool, [hashtable]$Arguments = @{}) {
        $response = Invoke-RestMethod -Uri "http://127.0.0.1:$($connection.port)/call" -Method Post -Headers @{'X-Prism-Token' = $connection.token} -ContentType 'application/json' -Body (@{tool=$Tool; args=$Arguments} | ConvertTo-Json -Depth 12) -TimeoutSec 30
        if (-not $response.ok) { throw "$Tool failed: $($response.error)" }
        return $response.result
    }
    $captures = @()
    foreach ($name in @('solid-distance-input', 'solid-distance-result', 'solid-two-sides-result', 'solid-symmetric-result', 'surface-open-chain-input', 'surface-open-chain-result', 'freeform-z-taper-open-result')) {
        $null = Call-Prism 'file' @{action='open'; path=(Join-Path $output ($name + '.prism'))}
        $null = Call-Prism 'view' @{preset='iso'; fit=$true; orthographic=$true; grid=$false; display='shaded_edges'}
        $null = Call-Prism 'wait_idle' @{extra_ms=1800}
        $state = Call-Prism 'get_state'
        $state | ConvertTo-Json -Depth 30 | Set-Content -LiteralPath (Join-Path $output ($name + '-viewport-state.json')) -Encoding utf8
        $shot = Call-Prism 'screenshot' @{viewport=$true; max_width=1100; wait_ms=500}
        $imagePath = Join-Path $output ($name + '-viewport.png')
        [IO.File]::WriteAllBytes($imagePath, [Convert]::FromBase64String($shot._image.data))
        $captures += $name + '-viewport.png'
        Write-Output "SCREENSHOT $imagePath"
    }
    @('# Actual desktop viewport captures', '', 'Captured through Prism automation screenshot(viewport=true); fixed isometric orthographic camera, fitted per model, grid off. Models come from the geometry test run; loading these snapshots does not test interactive command selection/preview. Camera and object state are saved alongside each PNG.', '') + @($captures | ForEach-Object { "![$_]($_)" }) | Set-Content -LiteralPath (Join-Path $output 'viewport-report.md') -Encoding utf8
}
finally {
    $env:PRISM_AUTOMATION_DISCOVERY = $oldDiscovery
    $env:PRISM_NO_HOME = $oldHome
    $env:PRISM_AUTOMATION = $oldAutomation
    if ($app -and -not $app.HasExited) { Stop-Process -Id $app.Id }
    if (Test-Path -LiteralPath $discovery) { Remove-Item -LiteralPath $discovery }
}
